"""Bundle the vendored we-scene shader translator into one plain script for the app's JS sandbox.

Each source file keeps its own function scope; ES module imports/exports are rewired through a
module table so the vendored files stay unmodified. Output: android/assets/we-shader-translator.js
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party' / 'we-scene'
OUTPUT = ROOT / 'android' / 'assets' / 'we-shader-translator.js'
# Dependency order: a module is defined before anything imports it.
MODULES = ['render/renderer-glsl.js', 'render/hlsl-preprocessor.js', 'render/hlsl2glsl.js', 'headers.ts']

IMPORT = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*["\']([^"\']+)["\'];?[ \t]*$', re.M)
EXPORT_LIST = re.compile(r'^export\s*\{([^}]*)\};?[ \t]*$', re.M)
EXPORT_DECL = re.compile(r'^export\s+(function|const|let|class)\s+([A-Za-z_$][\w$]*)', re.M)
ENTRY = r'''
globalThis.weTranslateShader = function (requestJson) {
  const request = JSON.parse(requestJson);
  const headers = __modules['headers'].WE_SHADER_HEADERS;
  const includes = request.includes || {};
  const resolve = (name) => {
    if (Object.prototype.hasOwnProperty.call(includes, name)) return includes[name];
    if (Object.prototype.hasOwnProperty.call(headers, name)) return headers[name];
    return null;
  };
  const hlsl = __modules['hlsl2glsl'].hlsl2glsl;
  // Wallpaper Engine accepts uniforms declared after an #include that uses them (e.g. common_blur.h reads
  // g_Texture0); GLSL needs the declaration first. Unconditional uniforms move above the first include.
  const hoistUniforms = (source) => {
    if (typeof source !== 'string') return source;
    const lines = source.replace(/\r\n/g, '\n').split('\n'), kept = [], moved = [];
    let depth = 0, include = -1;
    for (const line of lines) {
      const t = line.trim();
      if (/^#\s*if/.test(t)) depth++;
      else if (/^#\s*endif/.test(t)) depth = Math.max(0, depth - 1);
      if (include < 0 && depth === 0 && /^#\s*include\b/.test(t)) include = kept.length;
      if (include >= 0 && depth === 0 && /^uniform\s[^;]*;/.test(t)) { moved.push(line); continue; }
      kept.push(line);
    }
    if (!moved.length) return source;
    kept.splice(include, 0, ...moved);
    return kept.join('\n');
  };
  // GLSL's % takes integers only, so any % left in the output has integer operands; the translator can still
  // wrap an int() operand in float() (i % int(4) -> i % float(int(4))), which no GLSL compiler accepts.
  const INT = '(int\\((?:[^()]|\\([^()]*\\))*\\))';
  const fixModulo = (glsl) => typeof glsl !== 'string' ? glsl : glsl
    .replace(new RegExp('%(\\s*)float\\(\\s*' + INT + '\\s*\\)', 'g'), '%$1$2')
    .replace(new RegExp('float\\(\\s*' + INT + '\\s*\\)(\\s*)%', 'g'), '$1$2%');
  const translate = (source, stage, combos, include, other) => fixModulo(hlsl(hoistUniforms(source), stage, combos, include, hoistUniforms(other)));
  const combos = request.combos || {};
  return JSON.stringify({
    vertex: translate(request.vertex, 'vert', combos, resolve, request.fragment),
    fragment: translate(request.fragment, 'frag', combos, resolve, request.vertex),
  });
};
'''


def key(path):
    return pathlib.PurePosixPath(path).stem


def names(listing):
    return [part.split(' as ')[-1].strip() for part in listing.split(',') if part.strip()]


def wrap(path):
    text = (SOURCE / path).read_text(encoding='utf-8').replace('\r\n', '\n')
    if path.endswith('.ts'):
        # headers.ts carries exactly one type annotation, on its exported table.
        text, count = re.subn(r'(const\s+WE_SHADER_HEADERS)\s*:\s*Record<string,\s*string>', r'\1', text)
        if count != 1:
            raise SystemExit('Unexpected TypeScript syntax in ' + path)
    imports = []
    for listing, target in IMPORT.findall(text):
        imports.append('const { ' + ', '.join(names(listing)) + " } = __modules['" + key(target) + "'];")
    text = IMPORT.sub('', text)
    exported = [name for _, name in EXPORT_DECL.findall(text)]
    text = EXPORT_DECL.sub(r'\1 \2', text)
    for listing in EXPORT_LIST.findall(text):
        exported += names(listing)
    text = EXPORT_LIST.sub('', text)
    if re.search(r'^\s*(import|export)\b', text, re.M):
        raise SystemExit('Unhandled module syntax in ' + path)
    body = '\n'.join(imports) + '\n' + text + '\nreturn { ' + ', '.join(sorted(set(exported))) + ' };'
    return "__modules['" + key(path) + "'] = (function () {\n" + body + '\n})();\n'


def bundle():
    parts = ['// Generated by tools/bundle_shader_translator.py from third_party/we-scene (MIT). Do not edit.\n',
             "'use strict';\nconst __modules = {};\n"]
    parts += [wrap(path) for path in MODULES]
    parts.append(ENTRY)
    return ''.join(parts)


def main():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    content = bundle()
    if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
        OUTPUT.write_text(content, encoding='utf-8', newline='\n')
    print('Shader translator bundle:', OUTPUT.relative_to(ROOT), len(content), 'chars', flush=True)
    export_blending()


BLENDING = ROOT / 'android' / 'assets' / 'we-blending.glsl'


def export_blending():
    """WE common_blending.h exactly as the vendored renderer's WE_BLENDING_GLSL template literal evaluates."""
    source = (SOURCE / 'render' / 'renderer-glsl.js').read_text(encoding='utf-8').replace('\r\n', '\n')
    marker = 'const WE_BLENDING_GLSL = `'
    start = source.index(marker) + len(marker); end = start
    while source[end] != '`':
        end += 2 if source[end] == '\\' else 1
    literal = source[start:end]
    if '${' in literal:
        raise SystemExit('WE_BLENDING_GLSL gained interpolation; update export_blending')
    text = re.sub(r'\\(.)', lambda m: m.group(1), literal)
    if 'ApplyBlending' not in text:
        raise SystemExit('Blending header missing from the vendored renderer')
    text = '// Generated by tools/bundle_shader_translator.py from third_party/we-scene (MIT). Do not edit.\n' + text
    if not BLENDING.exists() or BLENDING.read_text(encoding='utf-8') != text:
        BLENDING.write_text(text, encoding='utf-8', newline='\n')
    print('Blending header:', BLENDING.relative_to(ROOT), len(text), 'chars', flush=True)


if __name__ == '__main__':
    main()
